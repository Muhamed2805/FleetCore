// Regenerates src/lib/supabase/database.types.ts from supabase/migrations.
//
// Starts a throwaway Postgres 17 container, adds the Supabase pieces the
// migrations rely on (scripts/supabase-stub.sql), applies every migration in
// order, then runs the Supabase CLI type generator against that database.
// The types always match the migrations in the repo, no Supabase login is
// needed, and every run also proves that all migrations apply cleanly.
//
// Needs Docker. CI runs it and fails when the committed file is out of date.
//
//   npm run db:types

import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const migrationsDir = path.join(root, "supabase", "migrations");
const stubFile = path.join(root, "scripts", "supabase-stub.sql");
const outFile = path.join(root, "src", "lib", "supabase", "database.types.ts");
const supabaseCli = path.join(root, "node_modules", "supabase", "dist", "supabase.js");
const oxfmtCli = path.join(root, "node_modules", "oxfmt", "bin", "oxfmt");

const image = "postgres:17-alpine";
const container = `fleetcore-db-types-${process.pid}`;

const header = `// Generated by \`npm run db:types\` from supabase/migrations. Don't edit by
// hand: add a migration, then regenerate.

`;

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { encoding: "utf8", ...options });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(
      `${path.basename(command)} ${args.slice(0, 3).join(" ")} failed:\n${result.stderr || result.stdout}`
    );
  }
  return result.stdout;
}

function sleep(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

// Each file runs in its own transaction and stops at the first error, like
// a migration should.
function applySql(file) {
  run(
    "docker",
    ["exec", "-i", container, "psql", "-q", "-v", "ON_ERROR_STOP=1", "-U", "postgres", "-1", "-f", "-"],
    { input: readFileSync(file, "utf8") }
  );
}

function waitForPostgres() {
  // Checked over TCP: during first start the image runs a temporary server
  // on the Unix socket only, which would look ready too early.
  for (let attempt = 0; attempt < 60; attempt += 1) {
    const ready = spawnSync("docker", [
      "exec", container, "pg_isready", "-h", "127.0.0.1", "-U", "postgres",
    ]);
    if (ready.status === 0) return;
    sleep(500);
  }
  throw new Error("Postgres did not start within 30 seconds");
}

try {
  console.log(`Starting ${image}…`);
  run("docker", [
    "run", "-d", "--rm", "--name", container,
    "-e", "POSTGRES_PASSWORD=postgres",
    "-p", "127.0.0.1::5432",
    "--tmpfs", "/var/lib/postgresql/data",
    image,
  ]);
  waitForPostgres();
  const port = run("docker", ["port", container, "5432/tcp"]).trim().split(":").pop();

  applySql(stubFile);
  const migrations = readdirSync(migrationsDir).filter((name) => name.endsWith(".sql")).sort();
  for (const name of migrations) {
    try {
      applySql(path.join(migrationsDir, name));
    } catch (error) {
      throw new Error(`Migration ${name} failed to apply.\n${error.message}`);
    }
  }
  console.log(`Applied ${migrations.length} migrations.`);

  const types = run(process.execPath, [
    supabaseCli, "gen", "types", "typescript",
    "--db-url", `postgresql://postgres:postgres@127.0.0.1:${port}/postgres?sslmode=disable`,
    "--schema", "public",
  ]);
  writeFileSync(outFile, header + types);
  run(process.execPath, [oxfmtCli, outFile]);
  console.log(`Wrote ${path.relative(root, outFile)}.`);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
} finally {
  spawnSync("docker", ["rm", "-f", container], { stdio: "ignore" });
}
